    test_status VARCHAR(32) NOT NULL DEFAULT 'NOT_STARTED' COMMENT '测试状态：NOT_STARTED/TESTING/PASSED',
    baseline_id BIGINT NULL COMMENT '所属基线版本',
    source VARCHAR(16) NOT NULL DEFAULT 'ONLINE' COMMENT '来源：ONLINE/IMPORT',
    import_batch_id BIGINT NULL COMMENT '导入批次',
    created_by BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0,
    KEY idx_req_difference_project (tenant_id, project_id),
    KEY idx_req_difference_review (tenant_id, review_status),
    KEY idx_req_difference_system (tenant_id, system_id),
    KEY idx_req_difference_no (tenant_id, requirement_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='新建项目需求差异清单（附件1 24 字段 + 生命周期扩展）';

