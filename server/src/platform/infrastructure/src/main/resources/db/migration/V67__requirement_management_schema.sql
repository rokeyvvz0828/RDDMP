-- 需求管理平台：新建项目差异清单、存量需求阶段、系统清单、基线、统一改动记录与导入批次。
-- 全部表使用 req_ 前缀，包含 tenant_id、软删除与审计字段；仅追加新表，不修改历史迁移。

CREATE TABLE req_system (
    id BIGINT PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    system_code VARCHAR(64) NOT NULL COMMENT '系统编号',
    system_name VARCHAR(128) NOT NULL COMMENT '系统名称',
    english_name VARCHAR(128) NULL COMMENT '英文简称',
    conglomerate VARCHAR(64) NULL COMMENT '事业群',
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' COMMENT '状态：ACTIVE/INACTIVE',
    logical_subsystem_code VARCHAR(64) NULL COMMENT '所属逻辑子系统编号',
    logical_subsystem_name VARCHAR(128) NULL COMMENT '所属逻辑子系统名称',
    business_component_code VARCHAR(64) NULL COMMENT '归属业务组件编号',
    business_component_name VARCHAR(128) NULL COMMENT '归属业务组件名称',
    business_domain VARCHAR(128) NULL COMMENT '业务领域',
    product_view VARCHAR(128) NULL COMMENT '产品视图',
    launch_point VARCHAR(128) NULL COMMENT '投产点',
    category VARCHAR(64) NULL COMMENT '类别',
    introduction VARCHAR(1000) NULL COMMENT '系统介绍',
    disaster_level VARCHAR(64) NULL COMMENT '灾备等级',
    source_type VARCHAR(32) NULL COMMENT '引入/保留',
    created_by BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_req_system_code (tenant_id, system_code),
    KEY idx_req_system_name (tenant_id, system_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='需求管理系统清单主数据';

CREATE TABLE req_project (
    id BIGINT PRIMARY KEY,
    tenant_id BIGINT NOT NULL DEFAULT 1,
    project_code VARCHAR(64) NOT NULL COMMENT '项目编码',
    project_name VARCHAR(200) NOT NULL COMMENT '项目名称',
    project_type VARCHAR(32) NOT NULL DEFAULT 'NEW_PROJECT' COMMENT '项目类型：NEW_PROJECT 0~1 新建',
    start_time DATE NULL COMMENT '启动时间',
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' COMMENT '状态：ACTIVE/BASELINED/CLOSED',
    description VARCHAR(1000) NULL COMMENT '说明',
    created_by BIGINT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_req_project_code (tenant_id, project_code),
    KEY idx_req_project_status (tenant_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='新建项目主数据';

